import os
import json
import time
import threading
from http.server import BaseHTTPRequestHandler, HTTPServer
from response.orchestrator import get_response_orchestrator, ResponseAction

# 1. Setup a dummy webhook server to intercept the SOAR call
class WebhookInterceptor(BaseHTTPRequestHandler):
    intercepted_payload = None
    
    def do_POST(self):
        content_length = int(self.headers['Content-Length'])
        post_data = self.rfile.read(content_length)
        WebhookInterceptor.intercepted_payload = json.loads(post_data.decode('utf-8'))
        self.send_response(200)
        self.end_headers()
        self.wfile.write(b'{"status": "success"}')

    def log_message(self, format, *args):
        pass # Suppress default logging

def run_server():
    server = HTTPServer(('localhost', 9999), WebhookInterceptor)
    server.timeout = 2.0
    server.handle_request()

# 2. Run the server in a background thread
server_thread = threading.Thread(target=run_server)
server_thread.daemon = True
server_thread.start()
time.sleep(0.5)

# 3. Configure the Orchestrator to point to our mock SOAR platform
os.environ["SOAR_WEBHOOK_URL"] = "http://localhost:9999/api/alert"
os.environ["SOAR_API_KEY"] = "mock_thehive_api_key_12345"

orchestrator = get_response_orchestrator()
orchestrator.execution_mode = "REAL_PRODUCTION"
orchestrator._dry_run = False

# 4. Create a mock action that would be generated by the Conformal Gate
action = ResponseAction(
    action_id="ACT-9999",
    action_type="ISOLATE_HOST",
    entity_key="10.0.1.55",
    target_identifier="10.0.1.55",
    risk_score=0.92,
    severity="CRITICAL",
    status="APPROVED",
    executed_at=None, details={"reason": "High confidence lateral movement detected via GNN", "conformal_tau": 0.12}
)

# 5. Execute the action (this will trigger the requests.post)
print("[*] Triggering SOAR Orchestrator execution...")
orchestrator._execute_action(action)

time.sleep(0.5)

# 6. Verify the intercept
if WebhookInterceptor.intercepted_payload:
    print("\n[+] SUCCESS! Webhook intercepted the SOAR payload formatted for TheHive/Shuffle:")
    print(json.dumps(WebhookInterceptor.intercepted_payload, indent=2))
else:
    print("\n[-] FAILED to intercept webhook.")

